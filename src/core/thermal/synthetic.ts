import { seededRandom } from '../xrd/synthetic';
import type { ThermalTable } from './types';

/** Standard normal cumulative distribution Φ(z), by Simpson's rule on the density (error < 1e-10). */
export function normalCdf(z: number): number {
  const upper = Math.max(-8, Math.min(8, z));
  const intervals = 400;
  const h = (upper + 8) / intervals;
  let sum = 0;
  for (let i = 0; i <= intervals; i++) {
    const x = -8 + i * h;
    const weight = i === 0 || i === intervals ? 1 : i % 2 === 1 ? 4 : 2;
    sum += weight * Math.exp(-0.5 * x * x);
  }
  return (sum * h) / 3 / Math.sqrt(2 * Math.PI);
}

/** A made-up mass loss step whose DTG is a Gaussian: area = `loss`, centre = `peak`. */
export interface SyntheticStep {
  /** Mass lost in the step, % of the starting mass. */
  loss: number;
  /** Temperature of the fastest mass loss, °C. */
  peak: number;
  /** Standard deviation of the DTG peak, °C. */
  sigma: number;
}

/** Mass in % at temperature t: 100 − Σ loss · Φ((t − peak) / σ). */
export function syntheticMassPct(t: number, steps: readonly SyntheticStep[]): number {
  let mass = 100;
  for (const s of steps) mass -= s.loss * normalCdf((t - s.peak) / s.sigma);
  return mass;
}

/** The made-up steps of the example run. */
export const EXAMPLE_STEPS: readonly SyntheticStep[] = [
  { loss: 9, peak: 120, sigma: 14 },
  { loss: 32, peak: 410, sigma: 22 },
  { loss: 11, peak: 640, sigma: 18 },
];

export const EXAMPLE_INITIAL_MASS_MG = 10;
export const EXAMPLE_HEATING_RATE = 10;

/**
 * A synthetic TGA run as a text table (temperature °C, time min, mass mg): heating from 30 to
 * 800 °C at 10 K/min with the steps above and a little noise, then a short hold and cooling,
 * which the cleaning step cuts off. Not a measurement of any real material.
 */
export function exampleTgaTable(): ThermalTable {
  const random = seededRandom(21);
  const temperature: number[] = [];
  const time: number[] = [];
  const mass: number[] = [];
  const noise = () =>
    Math.sqrt(-2 * Math.log(random() || 1e-12)) * Math.cos(2 * Math.PI * random());
  const add = (t: number, minutes: number, pct: number) => {
    temperature.push(t);
    time.push(minutes);
    mass.push(((pct + 0.03 * noise()) * EXAMPLE_INITIAL_MASS_MG) / 100);
  };
  for (let t = 30; t <= 800; t += 0.5) {
    add(t, (t - 30) / EXAMPLE_HEATING_RATE, syntheticMassPct(t, EXAMPLE_STEPS));
  }
  const end = syntheticMassPct(800, EXAMPLE_STEPS);
  for (let k = 1; k <= 20; k++) add(800, 77 + k * 0.5, end); // hold
  for (let k = 1; k <= 60; k++) add(800 - 5 * k, 87 + k * 0.5, end); // cooling
  return {
    names: ['Temperature °C', 'Time min', 'Mass mg'],
    columns: [Float64Array.from(temperature), Float64Array.from(time), Float64Array.from(mass)],
    headerText: 'Synthetic example generated by this site',
    notes: [
      {
        level: 'info',
        text: 'Synthetic example generated by this site (three made-up mass loss steps with a little noise). It is not a measurement of any real material.',
      },
    ],
  };
}

/** Sample mass of the DSC example, mg. */
export const EXAMPLE_DSC_MASS_MG = 5;
/** Scan rate of the DSC example, K/min. */
export const EXAMPLE_DSC_RATE = 10;

/** A made-up DSC event: Gaussian in temperature with enthalpy `enthalpy` (J/g, endothermic positive). */
export interface SyntheticDscEvent {
  name: string;
  /** Which scans it appears in. */
  scans: ('heating1' | 'cooling' | 'heating2')[];
  enthalpy: number;
  peakC: number;
  sigmaC: number;
}

/** The made-up events of the DSC example (a polymer-like heat-cool-heat run). */
export const EXAMPLE_DSC_EVENTS: readonly SyntheticDscEvent[] = [
  { name: 'cold crystallisation', scans: ['heating1'], enthalpy: -25, peakC: 105, sigmaC: 5 },
  { name: 'melting', scans: ['heating1'], enthalpy: 42, peakC: 165, sigmaC: 6 },
  { name: 'crystallisation', scans: ['cooling'], enthalpy: -30, peakC: 125, sigmaC: 6 },
  { name: 'melting', scans: ['heating2'], enthalpy: 40, peakC: 163, sigmaC: 6 },
];

/** Glass transition of the DSC example: midpoint °C and width of the logistic step, and ΔC_p in J/(g·K). */
export const EXAMPLE_DSC_GLASS = { heatingC: 60, coolingC: 58, widthC: 2, deltaCp: 0.3 };

/**
 * A synthetic DSC run as a text table (temperature °C, time min, heat flow mW, exo up): heat from
 * 25 to 220 °C at 10 K/min, hold 2 min, cool back, hold 1 min, heat again. The heat flow into the
 * sample is e = β·C_p(T) + Σ events, with β the signed scan rate in K/s, a C_p that rises linearly
 * and steps up at the glass transition, and Gaussian events whose areas are set from their
 * enthalpies (area = ΔH · β). The file value is −e · mass (exo up). Not a measurement.
 */
export function exampleDscTable(): ThermalTable {
  const random = seededRandom(33);
  const noise = () =>
    Math.sqrt(-2 * Math.log(random() || 1e-12)) * Math.cos(2 * Math.PI * random());
  const temperature: number[] = [];
  const time: number[] = [];
  const heatFlow: number[] = [];
  const rate = EXAMPLE_DSC_RATE;
  const secondsPerStep = 0.25 / (rate / 60);
  let clock = 0;
  const add = (t: number, scan: 'heating1' | 'cooling' | 'heating2' | null, tg: number) => {
    let e = 0;
    if (scan !== null) {
      const beta = (scan === 'cooling' ? -rate : rate) / 60;
      const step = 1 / (1 + Math.exp(-(t - tg) / EXAMPLE_DSC_GLASS.widthC));
      e = beta * (1.2 + 0.003 * (t - 25) + EXAMPLE_DSC_GLASS.deltaCp * step);
      for (const event of EXAMPLE_DSC_EVENTS) {
        if (!event.scans.includes(scan)) continue;
        const area = (event.enthalpy * rate) / 60; // W/g · K
        const amplitude = area / (event.sigmaC * Math.sqrt(2 * Math.PI));
        e += amplitude * Math.exp(-0.5 * ((t - event.peakC) / event.sigmaC) ** 2);
      }
    }
    temperature.push(t);
    time.push(clock / 60);
    heatFlow.push(-(e + 0.0004 * noise()) * EXAMPLE_DSC_MASS_MG);
    clock += secondsPerStep;
  };
  const glassUp = EXAMPLE_DSC_GLASS.heatingC;
  for (let t = 25; t <= 220; t += 0.25) add(t, 'heating1', glassUp);
  for (let k = 0; k < 80; k++) add(220, null, glassUp);
  for (let t = 219.75; t >= 25; t -= 0.25) add(t, 'cooling', EXAMPLE_DSC_GLASS.coolingC);
  for (let k = 0; k < 40; k++) add(25, null, glassUp);
  for (let t = 25.25; t <= 220; t += 0.25) add(t, 'heating2', glassUp);
  return {
    names: ['Temperature °C', 'Time min', 'Heat flow mW (exo up)'],
    columns: [Float64Array.from(temperature), Float64Array.from(time), Float64Array.from(heatFlow)],
    headerText: 'Synthetic example generated by this site',
    notes: [
      {
        level: 'info',
        text: 'Synthetic example generated by this site (a heat-cool-heat run with made-up events). It is not a measurement of any real material.',
      },
    ],
  };
}
