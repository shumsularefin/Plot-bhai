/**
 * Methods paragraph for a paper, written from the settings the analysis used. Every number comes
 * from the input; parts that were not used are left out, and nothing is said about the
 * instrument because a data file does not state it reliably.
 */
export interface ThermalMethodsInput {
  /** True when the only data is the generated example; then no measurement is described. */
  synthetic: boolean;
  /** Name of the gas, for example "nitrogen". */
  atmosphere: string;
  heatingRate: number | null;
  initialMassMg: number | null;
  sample: string;
  rangeC: { fromC: number; toC: number };
  smoothWindowC: number;
  blankSubtracted: boolean;
  /** Temperature at which the mass was set to 100 %, or null for the start of the run. */
  normaliseAtC: number | null;
  dtgWindowC: number;
  prominencePercent: number;
  minSeparationC: number;
  /** True when the step limits were moved or steps were added or removed by hand. */
  limitsEdited: boolean;
  stepCount: number;
  /** Events the user accepted or typed in, each with its step's DTG peak temperature. */
  events: { peakC: number; name: string }[];
  theory: { reaction: string; theoreticalPct: number; measuredPct: number } | null;
  calcination: { thresholdPct: number; marginC: number; minimumC: number } | null;
}

const rounded = (value: number, digits = 1) => value.toFixed(digits);

export function thermalMethodsParagraph(input: ThermalMethodsInput): string {
  if (input.synthetic) {
    return 'The curve analysed here is the synthetic example generated by the web tool. It is not a measurement, so there is nothing to report in a Methods section.';
  }
  const parts: string[] = [];
  const run = [
    `Thermogravimetric data were recorded in ${input.atmosphere}`,
    input.heatingRate !== null ? ` at a heating rate of ${rounded(input.heatingRate)} K min⁻¹` : '',
    input.initialMassMg !== null
      ? ` with an initial sample mass of ${rounded(input.initialMassMg, 2)} mg`
      : '',
    input.sample.trim() ? ` (sample: ${input.sample.trim()})` : '',
    '.',
  ].join('');
  parts.push(run);

  const prep = [
    `The heating ramp from ${rounded(input.rangeC.fromC, 0)} to ${rounded(input.rangeC.toC, 0)} °C was analysed`,
    input.blankSubtracted ? ', after subtracting a blank (empty crucible) run' : '',
    input.smoothWindowC > 0
      ? `, with the mass smoothed over a ${rounded(input.smoothWindowC, 0)} °C window`
      : '',
    input.normaliseAtC !== null
      ? `, and the mass set to 100 % at ${rounded(input.normaliseAtC, 0)} °C`
      : '',
    '.',
  ].join('');
  parts.push(prep);

  parts.push(
    `The derivative thermogravimetric (DTG) curve, −dm/dT, was calculated by a local quadratic least-squares fit over a ${rounded(input.dtgWindowC, 0)} °C window. Mass loss steps were taken from DTG peaks with a prominence of at least ${rounded(input.prominencePercent, 0)} % of the tallest peak and a minimum separation of ${rounded(input.minSeparationC, 0)} °C${input.limitsEdited ? ', and their limits were adjusted by hand' : ''}; ${input.stepCount} ${input.stepCount === 1 ? 'step was' : 'steps were'} found. Onset and endset temperatures are extrapolated tangent intersections (the tangent at the DTG maximum meets the mass before and after the step), and mass loss is the mass difference between the step limits.`,
  );

  if (input.events.length > 0) {
    parts.push(
      `Events were assigned from a table of typical temperature ranges as suggestions only (${input.events.map((e) => `${rounded(e.peakC, 0)} °C: ${e.name}`).join('; ')}); thermogravimetry alone does not identify the evolved species.`,
    );
  }
  if (input.theory) {
    parts.push(
      `The measured loss of the matching step (${rounded(input.theory.measuredPct)} %) was compared with the theoretical loss of ${input.theory.reaction} (${rounded(input.theory.theoreticalPct)} %), calculated from the CIAAW abridged standard atomic weights.`,
    );
  }
  if (input.calcination) {
    parts.push(
      `A minimum calcination temperature of ${rounded(input.calcination.minimumC, 0)} °C was suggested as the endset of the last step losing at least ${rounded(input.calcination.thresholdPct)} % plus a margin of ${rounded(input.calcination.marginC, 0)} °C; this is a starting point to be confirmed experimentally.`,
    );
  }
  return parts.join(' ');
}
