import { concentrationFrom } from '../../../core/uvvis/concentration';
import { formatNumber } from '../../../core/xrd/parsers/numbers';
import type { Outcome } from './analysis';
import type { ConcentrationData } from './data';

const n = (v: number, digits = 3) => formatNumber(v, digits);
const sig = (v: number) =>
  Math.abs(v) >= 1e4 || Math.abs(v) < 1e-3 ? v.toExponential(3) : n(v, 4);

/** A methods paragraph written only from the settings used and the numbers found. */
export function methodsText(data: ConcentrationData, outcome: Outcome): string {
  const parts: string[] = [];
  const synthetic = data.samples.some((s) => s.spectrum?.synthetic);
  if (outcome.wavelengthNm !== null) {
    parts.push(
      `Absorbance was read at ${n(outcome.wavelengthNm, 1)} nm${data.halfWidthNm > 0 ? ` (mean over ±${n(data.halfWidthNm, 1)} nm)` : ''}${data.wavelengthNm === null ? ', the absorption maximum of the reference spectrum' : ''}.`,
    );
  }
  const cal = outcome.calibration;
  if (cal) {
    const u = data.unit || 'concentration units';
    parts.push(
      `A calibration line A = ${cal.fit.intercept === 0 && data.throughOrigin ? '' : `${sig(cal.fit.intercept)} + `}${sig(cal.fit.slope)} c (c in ${u}) was fitted by least squares${data.throughOrigin ? ' through the origin' : ''} to ${cal.fit.n} standards from ${n(cal.range[0])} to ${n(cal.range[1])} ${u} (R² = ${cal.fit.rSquared.toFixed(4)}). With a path length of ${n(data.pathCm, 2)} cm the absorptivity (Beer–Lambert law, A = ε b c) is ε = ${sig(cal.absorptivity)} ± ${sig(cal.absorptivitySigma)} (${u})⁻¹ cm⁻¹ (standard error).`,
    );
  }
  const k = outcome.kinetics;
  if (k) {
    const last = k.points[k.points.length - 1];
    parts.push(
      `C/C₀ was taken as A/A₀ (Beer–Lambert law, same cell and wavelength), with C₀ the sample at t = ${n(k.referenceTimeMin, 1)} min. A pseudo-first-order model, ln(C₀/C) = k t, was fitted through the origin to ${k.fit.n} points, giving an apparent rate constant k = ${sig(k.kPerMin)} ± ${sig(k.kSigma)} min⁻¹ (R² = ${k.fit.rSquared.toFixed(4)})${k.halfLifeMin !== null ? ` and a half-life t½ = ln 2 / k = ${n(k.halfLifeMin, 1)} min` : ''}.${last ? ` After ${n(last.timeMin, 1)} min, ${n(last.removalPct, 1)} % had been removed (1 − C/C₀).` : ''}`,
    );
    if (cal && last) {
      parts.push(
        `With the calibration line, the concentration at the last time point is ${n(concentrationFrom(last.absorbance, cal))} ${data.unit}.`,
      );
    }
  }
  if (synthetic)
    parts.push('The data are a synthetic example generated by Plot Bhai, not measurements.');
  return parts.join(' ');
}
