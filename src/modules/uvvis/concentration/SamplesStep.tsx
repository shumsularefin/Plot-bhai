import { useState } from 'preact/hooks';
import { FileDrop } from '../../../ui/FileDrop';
import { HelpTip } from '../../../ui/HelpTip';
import type { StepContext } from '../../../ui/wizard/types';
import { NumberInput } from '../../xrd/NumberInput';
import { importSpectra } from '../importClient';
import type { ConcentrationData, ConcentrationSample, SampleRole } from './data';
import { exampleSamples } from './example';

const ROLE_TEXT: Record<
  SampleRole,
  { title: string; value: (unit: string) => string; intro: string; typed: string }
> = {
  standard: {
    title: 'Standards (known concentration)',
    value: (unit) => `Concentration (${unit || 'your unit'})`,
    intro:
      'Solutions of known concentration, for a calibration line (Beer–Lambert). Include a blank of concentration 0 if you measured one.',
    typed: 'Standard',
  },
  timed: {
    title: 'Samples over time (kinetics)',
    value: () => 'Time (min)',
    intro:
      'Samples taken during the experiment, for example during photocatalytic degradation. Use t = 0 for the moment the light was switched on; a dark period before it can have negative times.',
    typed: 'Sample',
  },
};

/** Step 1: load spectra (or type absorbances) for standards and for samples over time. */
export function SamplesStep({ data, update }: StepContext<ConcentrationData>) {
  const [problems, setProblems] = useState<string[]>([]);
  const [busy, setBusy] = useState(false);
  const { samples } = data;

  const patch = (id: string, change: Partial<ConcentrationSample>) =>
    update({ samples: samples.map((s) => (s.id === id ? { ...s, ...change } : s)) });

  const load = async (role: SampleRole, list: FileList | null) => {
    const files = list ? [...list] : [];
    if (files.length === 0) return;
    setBusy(true);
    const found: string[] = [];
    const added: ConcentrationSample[] = [];
    for (const file of files) {
      const result = await importSpectra({ kind: 'file', file });
      if (!result.ok) {
        found.push(`${file.name}: ${result.error}`);
        continue;
      }
      for (const s of result.spectra) {
        const spectrum = { ...s, id: crypto.randomUUID() };
        added.push({
          id: crypto.randomUUID(),
          role,
          name: s.name,
          spectrum,
          typedAbsorbance: null,
          value: null,
        });
      }
    }
    setBusy(false);
    setProblems(found);
    if (added.length > 0) update({ samples: [...samples, ...added] });
  };

  const addTyped = (role: SampleRole) => {
    const count = samples.filter((s) => s.role === role).length + 1;
    update({
      samples: [
        ...samples,
        {
          id: crypto.randomUUID(),
          role,
          name: `${ROLE_TEXT[role].typed} ${count}`,
          spectrum: null,
          typedAbsorbance: null,
          value: null,
        },
      ],
    });
  };

  return (
    <div class="upload-step">
      <p>
        Measure the concentration of a solution with a calibration line, follow it over time (for
        example dye degradation by a photocatalyst), or both. Every spectrum must be an absorbance
        or transmittance spectrum of a solution in the same cell.
      </p>
      {samples.length === 0 && (
        <div class="upload-actions">
          <button
            type="button"
            class="btn"
            onClick={() => update({ samples: exampleSamples(), wavelengthNm: null })}
          >
            Try with example data
          </button>
          <span class="field-hint">
            Loads five standards and a degradation series of a made-up dye, generated by this site.
            They are not real measurements.
          </span>
        </div>
      )}
      <p class="upload-status" role="status">
        {busy ? 'Reading the files…' : ''}
      </p>
      {problems.length > 0 && (
        <div class="import-problems" role="alert">
          <ul>
            {problems.map((p) => (
              <li key={p}>{p}</li>
            ))}
          </ul>
          <button type="button" class="btn btn-quiet" onClick={() => setProblems([])}>
            Dismiss
          </button>
        </div>
      )}

      {(['standard', 'timed'] as const).map((role) => {
        const text = ROLE_TEXT[role];
        const rows = samples.filter((s) => s.role === role);
        return (
          <section key={role} class="process-step is-on" aria-labelledby={`${role}-title`}>
            <h3 id={`${role}-title`} class="process-step-title">
              {text.title}
            </h3>
            <p class="field-hint">{text.intro}</p>
            {role === 'standard' && (
              <label class="inline-field">
                <span>
                  Concentration unit{' '}
                  <HelpTip term="concentration unit">
                    <p>
                      Any unit you like, for example mg/L, µmol/L or mol/L. With mol/L the
                      absorptivity is the molar absorption coefficient ε in L mol⁻¹ cm⁻¹.
                    </p>
                  </HelpTip>
                </span>
                <input
                  type="text"
                  value={data.unit}
                  onInput={(e) => update({ unit: e.currentTarget.value })}
                />
              </label>
            )}
            {rows.length > 0 && (
              <ul class="kinetic-runs">
                {rows.map((s) => (
                  <li key={s.id} class="run-form">
                    <label class="inline-field">
                      <span>Name</span>
                      <input
                        type="text"
                        value={s.name}
                        onInput={(e) => patch(s.id, { name: e.currentTarget.value })}
                      />
                    </label>
                    <NumberInput
                      label={`${text.value(data.unit)} of ${s.name}`}
                      value={s.value}
                      onChange={(v) => patch(s.id, { value: v })}
                    />
                    {s.spectrum ? (
                      <span class="field-hint">
                        Spectrum, {s.spectrum.kind}
                        {s.spectrum.synthetic && ' (synthetic)'}
                      </span>
                    ) : (
                      <NumberInput
                        label={`Absorbance of ${s.name}`}
                        value={s.typedAbsorbance}
                        onChange={(v) => patch(s.id, { typedAbsorbance: v })}
                      />
                    )}
                    <button
                      type="button"
                      class="btn btn-quiet"
                      onClick={() => update({ samples: samples.filter((x) => x.id !== s.id) })}
                    >
                      Remove<span class="visually-hidden"> {s.name}</span>
                    </button>
                  </li>
                ))}
              </ul>
            )}
            <FileDrop
              formats=".txt, .csv or .dat with wavelength and absorbance (or transmittance). Files stay on your device."
              onFiles={(files) => void load(role, files)}
              compact={rows.length > 0}
            />
            <button type="button" class="btn btn-quiet" onClick={() => addTyped(role)}>
              Type an absorbance instead
            </button>
          </section>
        );
      })}
    </div>
  );
}
