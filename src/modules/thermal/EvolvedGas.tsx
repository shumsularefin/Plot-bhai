const AXIS_LABELS: Record<EvolvedAxis, string> = {
  C: 'Temperature (°C)',
  K: 'Temperature (K)',
  min: 'Time (min)',
  s: 'Time (s)',
};

/** First column as x, read as time when its name says so; every other column is a signal. */
function guessEvolved(name: string, table: EvolvedFile['table'], synthetic = false): EvolvedFile {
  const first = table.names[0] ?? '';
  const axis: EvolvedAxis = /time|min/i.test(first)
    ? /\bs\b|sec|\(s\)|\[s\]/i.test(first)
      ? 's'
      : 'min'
    : /\bK\b|kelvin/.test(first)
      ? 'K'
      : 'C';
  const signals = table.names.map((_, i) => i).filter((i) => i > 0);
  return { name, table, xColumn: 0, axis, signals: signals.slice(0, MAX_SERIES - 1), synthetic };
}

/**
 * Made-up ion currents for the example run: two Gaussian signals at the first two example steps.
 * The column names are labels only; this site does not say which gas gives which signal.
 */
function exampleEvolved(): EvolvedFile {
  const T = Float64Array.from({ length: 771 }, (_, i) => 30 + i);
  const peak = (s: SyntheticStep, h: number) =>
    T.map((t) => 1e-11 + h * Math.exp(-0.5 * ((t - s.peak) / s.sigma) ** 2));
  return guessEvolved(
    'Example evolved gas signals (synthetic)',
    {
      names: ['Temperature (°C)', 'Signal A (A)', 'Signal B (A)'],
      columns: [
        T,
        peak(EXAMPLE_STEPS[0] as SyntheticStep, 4e-10),
        peak(EXAMPLE_STEPS[1] as SyntheticStep, 9e-10),
      ],
      headerText: 'Synthetic example generated by this site',
      notes: [],
    },
    true,
  );
}

const scaled = (y: Float64Array) => {
  let top = 0;
  for (const v of y) if (Number.isFinite(v)) top = Math.max(top, Math.abs(v));
  return top > 0 ? y.map((v) => v / top) : y;
};

interface EvolvedGasProps {
  data: ThermalData;
  update: (patch: Partial<ThermalData>) => void;
  curve: { temperatureC: Float64Array };
  dtg: Float64Array;
  steps: readonly StepResult[];
}

/**
 * Results section: evolved gas signals measured by a coupled mass spectrometer or FTIR, laid over
 * the DTG on one temperature axis. Each curve is scaled to its own maximum so their shapes and
 * positions can be compared; the table gives the temperature of each signal's maximum.
 */
export function EvolvedGas({ data, update, curve, dtg, steps }: EvolvedGasProps) {
  const [problem, setProblem] = useState<string | null>(null);
  const evolved = data.evolved;
  const run = useMemo(() => runOf(data.file), [data.file]);

  const temperatures = useMemo(() => {
    if (!evolved || !run) return null;
    const x = evolved.table.columns[evolved.xColumn];
    return x ? evolvedTemperatures(x, evolved.axis, run) : null;
  }, [evolved, run]);

  const signals = useMemo(() => {
    if (!evolved || !temperatures) return [];
    return evolved.signals.flatMap((i) => {
      const y = evolved.table.columns[i];
      if (!y || i === evolved.xColumn) return [];
      const name = evolved.table.names[i] ?? `Column ${i + 1}`;
      return [{ name, y, peak: signalPeak(temperatures, y, steps) }];
    });
  }, [evolved, temperatures, steps]);

  const sources = useMemo<SeriesSource[]>(() => {
    const list: SeriesSource[] = [
      { id: 'dtg', name: 'DTG', x: curve.temperatureC, y: scaled(dtg), unit: '', colorIndex: 0 },
    ];
    if (temperatures) {
      signals.forEach((s, i) =>
        list.push({
          id: `signal-${i}`,
          name: s.name,
          x: temperatures,
          y: scaled(s.y),
          unit: '',
          colorIndex: i + 1,
        }),
      );
    }
    return list;
  }, [curve, dtg, temperatures, signals]);

  const add = async (list: FileList | null) => {
    const file = list?.[0];
    if (!file) return;
    const result = importThermalFile(new Uint8Array(await file.arrayBuffer()));
    if (!result.ok) setProblem(`${file.name}: ${result.error}`);
    else if (result.table.columns.length < 2) {
      setProblem(`${file.name}: needs an x column and at least one signal column.`);
    } else {
      setProblem(null);
      update({ evolved: guessEvolved(file.name, result.table) });
    }
  };
  const set = (patch: Partial<EvolvedFile>) =>
    evolved && update({ evolved: { ...evolved, ...patch } });
  const timeWithoutTga =
    evolved && (evolved.axis === 'min' || evolved.axis === 's') && !run?.timeMin;

  return (
    <section aria-labelledby="evolved-title">
      <h3 id="evolved-title" class="export-title">
        Evolved gas signals (TGA–MS or TGA–FTIR){' '}
        <HelpTip term="evolved gas analysis">
          <p>
            TGA alone cannot tell which gas leaves the sample. A mass spectrometer or FTIR coupled
            to the balance can: load its export (one temperature or time column, then one column per
            ion current or band) to see which signals rise at each mass loss step. Naming the gas
            behind a signal is your interpretation; the site only shows where each signal is
            largest.
          </p>
        </HelpTip>
      </h3>
      <FileDrop
        formats=".txt, .csv or .dat: a temperature or time column, then signal columns. Files stay on your device."
        onFiles={(files) => void add(files)}
        compact
      />
      {!evolved && (
        <div class="upload-actions">
          <button type="button" class="btn" onClick={() => update({ evolved: exampleEvolved() })}>
            Try with example signals
          </button>
          <span class="field-hint">
            Adds two synthetic signals generated by this site. They are not real measurements.
          </span>
        </div>
      )}
      {problem && (
        <p class="message is-error" role="alert">
          {problem}
        </p>
      )}
      {evolved && (
        <>
          <div class="radiation-fields">
            <ColumnSelect
              label="x column"
              names={evolved.table.names}
              value={evolved.xColumn}
              onChange={(v) =>
                set({ xColumn: v ?? 0, signals: evolved.signals.filter((s) => s !== v) })
              }
            />
            <label class="inline-field">
              x is
              <select
                value={evolved.axis}
                onChange={(e) => set({ axis: e.currentTarget.value as EvolvedAxis })}
              >
                {(Object.keys(AXIS_LABELS) as EvolvedAxis[]).map((a) => (
                  <option key={a} value={a}>
                    {AXIS_LABELS[a]}
                  </option>
                ))}
              </select>
            </label>
            <button type="button" class="btn btn-quiet" onClick={() => update({ evolved: null })}>
              Remove the signals
            </button>
          </div>
          <fieldset class="method-choice">
            <legend>Signals to show</legend>
            {evolved.table.names.map((name, i) =>
              i === evolved.xColumn ? null : (
                <label key={i} class="check">
                  <input
                    type="checkbox"
                    checked={evolved.signals.includes(i)}
                    disabled={
                      !evolved.signals.includes(i) && evolved.signals.length >= MAX_SERIES - 1
                    }
                    onChange={(e) =>
                      set({
                        signals: e.currentTarget.checked
                          ? [...evolved.signals, i].sort((a, b) => a - b)
                          : evolved.signals.filter((s) => s !== i),
                      })
                    }
                  />
                  {name}
                </label>
              ),
            )}
          </fieldset>
          {timeWithoutTga && (
            <p class="message is-warning">
              <strong>Check:</strong> the signals are against time, but the TGA run has no time
              column to turn time into temperature. Choose a temperature column, or add the time
              column to the TGA run in Upload.
            </p>
          )}
          {evolved.axis !== 'C' && evolved.axis !== 'K' && !timeWithoutTga && (
            <p class="field-hint">
              Time was turned into temperature with the TGA run&apos;s own time and temperature
              columns, so both files must start the clock at the same moment. A transfer line delays
              the signals by a few seconds to minutes; this is not corrected.
            </p>
          )}
          {temperatures && signals.length > 0 && (
            <>
              <PlotPanel
                sources={sources}
                settings={data.plot}
                onSettingsChange={(p) => update({ plot: { ...data.plot, ...p } })}
                labels={() => ({ x: 'Temperature (°C)', y: 'Scaled to its own maximum' })}
                xName="T"
                xUnit=" °C"
                exportName="tga-evolved-gas"
                showOverlayOptions={false}
              />
              <div
                class="table-scroll"
                tabIndex={0}
                role="region"
                aria-label="Signal maxima, scrolls sideways"
              >
                <table class="peak-table">
                  <thead>
                    <tr>
                      <th scope="col">Signal</th>
                      <th scope="col">Largest at (°C)</th>
                      <th scope="col">Within mass loss step</th>
                    </tr>
                  </thead>
                  <tbody>
                    {signals.map((s) => (
                      <tr key={s.name}>
                        <th scope="row">{s.name}</th>
                        <td>{s.peak ? formatNumber(s.peak.peakC, 1) : '–'}</td>
                        <td>
                          {s.peak && s.peak.step !== null ? `Step ${s.peak.step + 1}` : 'none'}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
              <div class="export-actions">
                <button
                  type="button"
                  class="btn"
                  onClick={() =>
                    downloadCsv(
                      'tga-evolved-gas',
                      `Evolved gas signals from ${evolved.name}: temperature of each signal's maximum and the TGA step whose limits contain it. Assigning a gas to a signal is the user's interpretation.`,
                      signals,
                      [
                        { header: 'Signal', value: (s) => s.name },
                        { header: 'Largest at (C)', value: (s) => s.peak?.peakC ?? NaN },
                        {
                          header: 'Step',
                          value: (s) =>
                            (s.peak?.step ?? null) === null
                              ? ''
                              : `${(s.peak?.step as number) + 1}`,
                        },
                      ],
                    )
                  }
                >
                  Signal maxima (CSV)
                </button>
              </div>
            </>
          )}
        </>
      )}
    </section>
  );
}
