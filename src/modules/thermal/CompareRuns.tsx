import { useMemo, useState } from 'preact/hooks';
import { summariseRun, type RunSummary } from '../../core/thermal/compare';
import { cleanRun } from '../../core/thermal/process';
import { syntheticMassPct, type SyntheticStep } from '../../core/thermal/synthetic';
import { formatNumber } from '../../core/xrd/parsers/numbers';
import { FileDrop } from '../../ui/FileDrop';
import { HelpTip } from '../../ui/HelpTip';
import { MAX_SERIES } from '../../ui/plot/palette';
import { downloadCsv } from '../xrd/csv';
import { runOf } from './analysis';
import type { LoadedTable, ThermalData } from './data';
import { ThermalPlot, type MassCurve } from './ThermalPlot';
import { loadTable } from './UploadStep';

interface Row {
  id: string;
  name: string;
  synthetic: boolean;
  /** Null when the run could not be read or cleaned; `error` says why. */
  curve: { temperatureC: Float64Array; massPct: Float64Array } | null;
  summary: RunSummary | null;
  error: string | null;
}

/** Made-up samples for the example: the same three steps with more or less organic material. */
const EXAMPLE_SAMPLES: readonly { name: string; steps: SyntheticStep[] }[] = [
  {
    name: 'Example sample B (synthetic)',
    steps: [
      { loss: 6, peak: 115, sigma: 14 },
      { loss: 22, peak: 430, sigma: 22 },
      { loss: 8, peak: 650, sigma: 18 },
    ],
  },
  {
    name: 'Example sample C (synthetic)',
    steps: [
      { loss: 12, peak: 125, sigma: 14 },
      { loss: 40, peak: 380, sigma: 24 },
      { loss: 12, peak: 620, sigma: 18 },
    ],
  },
];

function exampleRun(sample: (typeof EXAMPLE_SAMPLES)[number]): LoadedTable {
  const temperature: number[] = [];
  for (let t = 30; t <= 800; t += 1) temperature.push(t);
  return {
    name: sample.name,
    table: {
      names: ['Temperature (°C)', 'Mass (%)'],
      columns: [
        Float64Array.from(temperature),
        Float64Array.from(temperature, (t) => syntheticMassPct(t, sample.steps)),
      ],
      headerText: 'Synthetic example generated by this site',
      notes: [],
    },
    mapping: {
      temperature: 0,
      temperatureUnit: 'C',
      mass: 1,
      massUnit: 'percent',
      time: null,
      timeUnit: 'min',
      heatFlow: null,
    },
    synthetic: true,
  };
}

const num = (value: number | null, digits = 1) =>
  value === null || !Number.isFinite(value) ? '–' : formatNumber(value, digits);

interface CompareRunsProps {
  data: ThermalData;
  update: (patch: Partial<ThermalData>) => void;
  /** This analysis's cleaned curve, the first row of the comparison. */
  curve: { temperatureC: Float64Array; massPct: Float64Array };
}

/**
 * Results section: other samples' TGA runs overlaid on this one, with T5, T10, T50, the
 * residue and the fastest mass loss for each. Every run is cleaned with this analysis's
 * settings, without a blank, and its first mass value is 100 %.
 */
export function CompareRuns({ data, update, curve }: CompareRunsProps) {
  const [problems, setProblems] = useState<string[]>([]);
  const { clean, steps, compare } = data;
  const settings = useMemo(() => ({ ...clean, useBlank: false }), [clean]);

  const rows = useMemo<Row[]>(() => {
    const summarise = (c: Row['curve']) =>
      c ? summariseRun(c.temperatureC, c.massPct, steps.dtgWindowC, steps.residueAtC) : null;
    const own: Row = {
      id: 'this',
      name: data.info.sample || data.file?.name || 'This sample',
      synthetic: data.file?.synthetic ?? false,
      curve,
      summary: summarise(curve),
      error: null,
    };
    const others = compare.map((loaded, i): Row => {
      const run = runOf(loaded);
      const cleaned = run ? cleanRun(run, null, { initialMassMg: null }, settings) : null;
      const c = cleaned?.ok ? cleaned.curve : null;
      return {
        id: `compare-${i}`,
        name: loaded.name,
        synthetic: loaded.synthetic,
        curve: c,
        summary: summarise(c),
        error: !run
          ? 'The temperature and mass columns could not be read.'
          : cleaned && !cleaned.ok
            ? cleaned.error
            : null,
      };
    });
    return [own, ...others];
  }, [data.info.sample, data.file, curve, compare, settings, steps]);

  const curves = useMemo<MassCurve[]>(
    () =>
      rows.flatMap((r, i) =>
        r.curve
          ? [
              {
                id: r.id,
                name: r.name,
                temperatureC: r.curve.temperatureC,
                mass: r.curve.massPct,
                colorIndex: i,
              },
            ]
          : [],
      ),
    [rows],
  );

  const room = MAX_SERIES - 1 - compare.length;
  const add = async (list: FileList | null) => {
    const files = list ? [...list] : [];
    const found: string[] = [];
    const added: LoadedTable[] = [];
    for (const [i, file] of files.entries()) {
      if (i >= room) {
        found.push(`${file.name}: up to ${MAX_SERIES} runs can be compared at once.`);
        continue;
      }
      const loaded = await loadTable(file);
      if (typeof loaded === 'string') found.push(`${file.name}: ${loaded}`);
      else if (loaded.mapping.mass === null) found.push(`${file.name}: no mass column was found.`);
      else added.push(loaded);
    }
    setProblems(found);
    if (added.length > 0) update({ compare: [...compare, ...added] });
  };

  const header = `TGA comparison. Every run cleaned with the same settings, no blank, 100 % = first mass value of each run. T5/T10/T50 = temperature at 95/90/50 % mass; fastest mass loss = maximum of DTG (${steps.dtgWindowC} C window). Temperatures in C.`;

  return (
    <section aria-labelledby="compare-title">
      <h3 id="compare-title" class="export-title">
        Compare with other samples{' '}
        <HelpTip term="comparing runs">
          <p>
            Load the TGA runs of other samples (for example different doping levels or synthesis
            temperatures). Each is cleaned with the settings of this analysis, without a blank, and
            its first mass value is set to 100 %, so the curves can be laid over each other. A
            higher T5, T10 or DTG peak temperature means the sample keeps its mass to a higher
            temperature. Compare runs measured at the same heating rate and atmosphere.
          </p>
        </HelpTip>
      </h3>
      <FileDrop
        formats=".txt, .csv or .dat with temperature and mass columns. Files stay on your device."
        onFiles={(files) => void add(files)}
        disabled={room <= 0}
        compact
      />
      {compare.length === 0 && (
        <div class="upload-actions">
          <button
            type="button"
            class="btn"
            onClick={() => update({ compare: EXAMPLE_SAMPLES.map(exampleRun) })}
          >
            Try with example samples
          </button>
          <span class="field-hint">
            Adds two synthetic runs generated by this site. They are not real measurements.
          </span>
        </div>
      )}
      {problems.length > 0 && (
        <ul class="message is-error" role="alert">
          {problems.map((p) => (
            <li key={p}>{p}</li>
          ))}
        </ul>
      )}
      {compare.length > 0 && (
        <>
          <div
            class="table-scroll"
            tabIndex={0}
            role="region"
            aria-label="Comparison table, scrolls sideways"
          >
            <table class="peak-table">
              <thead>
                <tr>
                  <th scope="col">Sample</th>
                  <th scope="col">T5 % (°C)</th>
                  <th scope="col">T10 % (°C)</th>
                  <th scope="col">T50 % (°C)</th>
                  <th scope="col">Fastest loss (°C)</th>
                  <th scope="col">
                    Residue at {steps.residueAtC === null ? '–' : num(steps.residueAtC, 0)} °C (%)
                  </th>
                  <th scope="col">Total loss (%)</th>
                  <th scope="col">
                    <span class="visually-hidden">Remove</span>
                  </th>
                </tr>
              </thead>
              <tbody>
                {rows.map((r, i) => (
                  <tr key={r.id}>
                    <th scope="row">{r.name}</th>
                    {r.summary ? (
                      <>
                        <td>{num(r.summary.t5)}</td>
                        <td>{num(r.summary.t10)}</td>
                        <td>{num(r.summary.t50)}</td>
                        <td>{num(r.summary.dtgPeakC)}</td>
                        <td>{num(r.summary.residuePct, 2)}</td>
                        <td>{num(r.summary.totalLossPct, 2)}</td>
                      </>
                    ) : (
                      <td colSpan={6} class="is-error">
                        {r.error ?? 'This run could not be used.'}
                      </td>
                    )}
                    <td>
                      {i > 0 && (
                        <button
                          type="button"
                          class="btn btn-quiet"
                          aria-label={`Remove ${r.name}`}
                          onClick={() => update({ compare: compare.filter((_, k) => k !== i - 1) })}
                        >
                          Remove
                        </button>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div class="export-actions">
            <button
              type="button"
              class="btn"
              onClick={() =>
                downloadCsv(
                  'tga-comparison',
                  header,
                  rows.filter((r) => r.summary),
                  [
                    { header: 'Sample', value: (r) => r.name },
                    { header: 'Synthetic', value: (r) => (r.synthetic ? 'yes' : 'no') },
                    { header: 'T5 (C)', value: (r) => r.summary?.t5 ?? '' },
                    { header: 'T10 (C)', value: (r) => r.summary?.t10 ?? '' },
                    { header: 'T50 (C)', value: (r) => r.summary?.t50 ?? '' },
                    { header: 'Fastest loss (C)', value: (r) => r.summary?.dtgPeakC ?? '' },
                    { header: 'Fastest loss (%/C)', value: (r) => r.summary?.dtgPeak ?? '' },
                    {
                      header: `Residue at ${steps.residueAtC ?? ''} C (%)`,
                      value: (r) => r.summary?.residuePct ?? '',
                    },
                    { header: 'Total loss (%)', value: (r) => r.summary?.totalLossPct ?? '' },
                  ],
                )
              }
            >
              Download comparison (CSV)
            </button>
          </div>
          <ThermalPlot
            curves={curves}
            massUnit="%"
            settings={data.plot}
            onSettingsChange={(p) => update({ plot: { ...data.plot, ...p } })}
            exportName="tga-comparison"
          />
        </>
      )}
    </section>
  );
}
